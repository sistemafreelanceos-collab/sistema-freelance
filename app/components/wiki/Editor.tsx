"use client";

import { useEditor, EditorContent } from '@tiptap/react';
import StarterKit from '@tiptap/starter-kit';
import Placeholder from '@tiptap/extension-placeholder';
import { useEffect } from 'react';

interface EditorProps {
    content: any; // JSON generated by Tiptap
    onChange: (content: any) => void;
    editable?: boolean;
    placeholder?: string;
}

export default function Editor({ content, onChange, editable = true, placeholder = 'Escribe aquí...' }: EditorProps) {
    const editor = useEditor({
        extensions: [
            StarterKit,
            Placeholder.configure({
                placeholder: placeholder,
            }),
        ],
        content: content,
        editable: editable,
        onUpdate: ({ editor }) => {
            onChange(editor.getJSON());
        },
        editorProps: {
            attributes: {
                class: 'prose prose-invert max-w-none focus:outline-none min-h-[200px]',
            },
        },
    });

    useEffect(() => {
        if (editor && content) {
            // Only update if content changed externally and is different
            // To avoid cursor jumping or loops, strict checks might be needed.
            // For now, we assume this is mostly initial load or distinct switch.
            const currentContent = editor.getJSON();
            if (JSON.stringify(currentContent) !== JSON.stringify(content)) {
                editor.commands.setContent(content);
            }
        }
    }, [content, editor]);

    if (!editor) {
        return null;
    }

    return (
        <div className="bg-black/20 border border-white/10 rounded-xl p-4 min-h-[300px] cursor-text" onClick={() => editor.chain().focus().run()}>
            {editable && (
                <div className="flex gap-2 mb-4 border-b border-white/10 pb-2 overflow-x-auto">
                    <button
                        onClick={() => editor.chain().focus().toggleBold().run()}
                        className={`p-1.5 rounded hover:bg-white/10 text-sm ${editor.isActive('bold') ? 'bg-white/10 text-emerald-400' : 'text-gray-400'}`}
                    >
                        Bold
                    </button>
                    <button
                        onClick={() => editor.chain().focus().toggleItalic().run()}
                        className={`p-1.5 rounded hover:bg-white/10 text-sm ${editor.isActive('italic') ? 'bg-white/10 text-emerald-400' : 'text-gray-400'}`}
                    >
                        Italic
                    </button>
                    <button
                        onClick={() => editor.chain().focus().toggleHeading({ level: 1 }).run()}
                        className={`p-1.5 rounded hover:bg-white/10 text-sm ${editor.isActive('heading', { level: 1 }) ? 'bg-white/10 text-emerald-400' : 'text-gray-400'}`}
                    >
                        H1
                    </button>
                    <button
                        onClick={() => editor.chain().focus().toggleHeading({ level: 2 }).run()}
                        className={`p-1.5 rounded hover:bg-white/10 text-sm ${editor.isActive('heading', { level: 2 }) ? 'bg-white/10 text-emerald-400' : 'text-gray-400'}`}
                    >
                        H2
                    </button>
                    <button
                        onClick={() => editor.chain().focus().toggleBulletList().run()}
                        className={`p-1.5 rounded hover:bg-white/10 text-sm ${editor.isActive('bulletList') ? 'bg-white/10 text-emerald-400' : 'text-gray-400'}`}
                    >
                        List
                    </button>
                    <button
                        onClick={() => editor.chain().focus().toggleCodeBlock().run()}
                        className={`p-1.5 rounded hover:bg-white/10 text-sm ${editor.isActive('codeBlock') ? 'bg-white/10 text-emerald-400' : 'text-gray-400'}`}
                    >
                        Code
                    </button>
                </div>
            )}
            <EditorContent editor={editor} />
        </div>
    );
}
